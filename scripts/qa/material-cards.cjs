const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { chromium } = require('playwright-core')

async function main() {
  const browser = await chromium.launch({
    executablePath: process.env.DSH_QA_BROWSER || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',
  })
  const page = await browser.newPage({ viewport: { width: 1800, height: 1100 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  const card = page.locator('.st-card.active')
  const editor = card.locator('[data-composer-input][contenteditable=true]')
  const dialog = page.locator('dialog.st-material-dialog')
  const contentInput = card.locator('.cm-content')
  const preview = card.getByRole('button', { name: '预览', exact: true })
  async function typeSource(text) {
    await contentInput.click()
    await page.keyboard.press('Control+a')
    if (text) {
      await page.evaluate(text => navigator.clipboard.writeText(text), text)
      await page.keyboard.press('Control+v')
    } else await page.keyboard.press('Backspace')
  }
  const toolbar = page.getByRole('toolbar', { name: '选中文字操作' })
  const root = '资料卡根节点 QA_LAYOUT_SCALE ' + Date.now()
  const branch = '资料卡划词提问 ' + Date.now()
  const whole = '整张代码卡追问 ' + Date.now()
  const codeQuote = '代码多行划词追问 ' + Date.now()
  const sibling = '资料卡兄弟节点 ' + Date.now()
  const oldText = 'V1_MARKDOWN_SELECTION', newText = 'V2_MARKDOWN_SELECTION'
  const clearSelection = () => page.evaluate(() => getSelection()?.removeAllRanges())
  async function active(text) {
    await page.waitForFunction(text => {
      const selected = document.querySelector('.st-card.active')
      return (selected?.querySelector('.st-question')?.textContent ?? selected?.getAttribute('aria-label')) === text
    }, text)
  }
  async function pick(text) {
    await clearSelection()
    await page.getByRole('button', { name: text, exact: true }).and(page.locator('.st-tree-title')).click()
    await active(text)
  }
  async function create(kind, name, content, language) {
    const add = page.getByRole('toolbar', { name: '画布工具' }).getByRole('button', { name: '添加卡片' })
    assert.equal(await page.locator('.st-bar').getByRole('button', { name: '添加卡片' }).count(), 0)
    await add.click()
    const popup = page.getByRole('group', { name: '选择卡片类型' })
    await popup.waitFor()
    assert.ok((await popup.boundingBox()).y < (await add.boundingBox()).y, '菜单应从工具栏上方展开')
    if (kind === 'Markdown') await page.screenshot({ path: path.join(process.env.DSH_QA_OUTPUT, 'add-card-toolbar.png') })
    await page.getByRole('button', { name: kind + '卡片', exact: true }).click()
    await contentInput.waitFor()
    assert.equal(await dialog.count(), 0)
    await editor.waitFor()
    assert.equal(await card.getByRole('button', { name: '完成', exact: true }).count(), 0)
    assert.ok(await contentInput.evaluate(el => document.activeElement === el), '新建资料后焦点应留在正文编辑器 ')
    assert.deepEqual(await card.evaluate(el => [el.offsetWidth, el.offsetHeight]), [768, 512])
    assert.equal(await card.locator('.st-card-composer').evaluate(el => getComputedStyle(el).position), 'absolute')
    await card.screenshot({ path: path.join(process.env.DSH_QA_OUTPUT, kind === '代码' ? 'empty-code-card.png' : 'material-inline-editor.png') })
    // Resize the newly created, still empty card before its first keystroke.
    const zoom = Number.parseInt(await page.locator('.st-zoom-value').innerText(), 10) / 100
    const handle = await card.locator('.react-flow__resize-control.handle.bottom.right').boundingBox()
    const x = handle.x + handle.width / 2, y = handle.y + handle.height / 2
    await page.mouse.move(x, y)
    await page.mouse.down()
    await page.mouse.move(x - 48 * zoom, y - 48 * zoom, { steps: 10 })
    await page.mouse.up()
    assert.ok(await card.evaluate(el => el.offsetWidth < 740 && el.offsetHeight < 490), '空卡应能立即调整尺寸')
    if (language) {
      const trigger = card.getByRole('button', { name: '代码语言' })
      const popup = page.getByRole('dialog', { name: '选择代码语言' })
      const search = popup.getByRole('combobox', { name: '搜索语言' })
      await trigger.click()
      await search.fill('NoSuchLanguage')
      await popup.getByText('没有匹配的语言').waitFor()
      await search.fill('ts')
      await popup.getByRole('option', { name: 'TypeScript' }).waitFor()
      await search.press('Escape')
      assert.equal(await trigger.innerText(), '纯文本')
      await trigger.click()
      await search.fill(language)
      await search.press('Enter')
      assert.equal(await trigger.innerText(), 'C++')
      await trigger.click()
      await popup.getByRole('option', { name: 'C++', selected: true }).waitFor()
      await search.press('ArrowDown')
      await popup.screenshot({ path: path.join(process.env.DSH_QA_OUTPUT, 'code-language-picker.png') })
      await popup.getByRole('option', { name: 'C++' }).click()
      await popup.waitFor({ state: 'hidden' })
    }
    await typeSource(content)
    if (kind === 'Markdown') {
      await preview.click()
      await card.locator('.st-material-rendered h1').waitFor()
    } else {
      await card.locator('.cm-content .st-token-keyword').first().waitFor()
      await page.waitForFunction(() => {
        const card = document.querySelector('.st-card.active')
        const line = card.querySelector('.cm-line').getBoundingClientRect()
        const number = [...card.querySelectorAll('.cm-lineNumbers .cm-gutterElement')].find(el => el.textContent === '1').getBoundingClientRect()
        return Math.abs(line.top - number.top) < 2
      })
      await card.screenshot({ path: path.join(process.env.DSH_QA_OUTPUT, 'code-editor.png') })
      await editor.click()
      assert.ok(await card.locator('.cm-content .st-token-keyword').count())
      assert.ok(await card.locator('.cm-lineNumbers .cm-gutterElement').count() >= 2)
    }
    await active(name)
    await editor.waitFor()
  }
  async function highlight(locator, from, length) {
    await locator.evaluate((element, { from, length }) => {
      const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT)
      const range = new Range()
      let start = false, offset = 0, node
      while ((node = walker.nextNode())) {
        if (!start && offset + node.length > from) { range.setStart(node, from - offset); start = true }
        if (start && offset + node.length >= from + length) { range.setEnd(node, from + length - offset); break }
        offset += node.length
      }
      const selection = getSelection()
      selection.removeAllRanges()
      selection.addRange(range)
      element.dispatchEvent(new MouseEvent('mouseup', { bubbles: true }))
    }, { from, length })
    await toolbar.waitFor()
  }
  try {
    const log = fs.readFileSync(process.env.DSH_QA_LOG, 'utf8')
    await page.goto(log.match(/http:\/\/\S+/)[0])
    await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
    await page.keyboard.press('Escape')
    await page.getByText('新会话', { exact: true }).first().click()
    await page.getByRole('button', { name: '以学习画布开始' }).click()
    const home = page.locator('[data-composer-input][contenteditable=true]').first()
    await home.fill(root)
    await home.press('Enter')
    await active(root)
    await editor.waitFor()
    const reader = page.locator('[data-slot="main.conversation"] [data-conversation-session]').first()
    const sessionId = await reader.getAttribute('data-conversation-session')
    const sessionFiles = () => fs.readdirSync(process.env.DSH_QA_SESSIONS, { recursive: true })
      .filter(name => /(?:^|[\\/])session(?:\.v\d+)?\.jsonl(?:\.zstd)?$/.test(name)).sort()
    const originalFiles = sessionFiles()
    assert.ok(originalFiles.length)
    await create('Markdown', '复习笔记', '# 复习笔记\n\n' + oldText + '\n\nV1_MARKDOWN_REMAINDER')
    await highlight(card.locator('.st-material-rendered').getByText(oldText, { exact: true }), 0, oldText.length)
    await toolbar.getByRole('button', { name: '添加到对话' }).click()
    await page.waitForFunction(text => document.querySelector('.st-card.active [data-composer-input]')?.textContent.includes(text), oldText)
    assert.equal(await page.locator('.st-card').count(), 2)
    await page.keyboard.press('Escape')
    await highlight(card.locator('.st-material-rendered').getByText(oldText, { exact: true }), 0, oldText.length)
    await toolbar.getByRole('button', { name: '在分支中提问' }).click()
    const quoteEditor = page.locator('.st-quote-popover [data-composer-input][contenteditable=true]')
    await quoteEditor.waitFor()
    await quoteEditor.fill('> ' + oldText + '\n\n' + branch + ' QA_LAYOUT_SCALE')
    await quoteEditor.press('Enter')
    await active(branch + ' QA_LAYOUT_SCALE')
    await editor.waitFor()
    await card.locator('.st-inlet[data-inlet="quote"]').waitFor({ state: 'attached' })
    await pick('复习笔记')
    if (await preview.getAttribute('aria-pressed') === 'true') await preview.click()
    await typeSource('# 复习笔记\n\n' + newText)
    await preview.click()
    await card.locator('.st-material-rendered').getByText(newText, { exact: true }).waitFor()
    await pick(branch + ' QA_LAYOUT_SCALE')
    await card.getByRole('button', { name: '定位引用原文：' + oldText }).click()
    await dialog.getByText('提问时的资料 · 第 2 版').waitFor()
    assert.ok((await dialog.innerText()).includes('V1_MARKDOWN_REMAINDER'))
    await dialog.getByRole('button', { name: '关闭资料' }).click()
    await pick(root)
    const answer = card.locator('.st-turn-flow').getByText('第三段是最终结果。本轮结束后才显示继续提问输入框。', { exact: true })
    await highlight(answer, 0, 4)
    await toolbar.getByRole('button', { name: '存为Markdown卡片' }).click()
    assert.equal(await contentInput.innerText(), '第三段是')
    assert.equal(await dialog.count(), 0)
    await active('第三段是')
    await card.getByRole('button', { name: '定位引用原文：第三段是' }).click()
    await active(root)
    const snippet = '#include <iostream>\nusing namespace std;\n\nint main() {\n    cout << "study tree" << endl;\n    return 0;\n}'
    await create('代码', '代码片段', snippet, 'cpp')
    const code = card.locator('.cm-content')
    await code.waitFor()
    const codeTools = card.getByRole('group', { name: '代码块工具' })
    const wrap = codeTools.getByRole('button', { name: '自动换行' })
    await wrap.click()
    assert.equal(await code.evaluate(el => el.classList.contains('cm-lineWrapping')), false)
    await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
    await codeTools.getByRole('button', { name: '复制代码' }).click()
    await codeTools.getByText('已复制').waitFor()
    const copied = await page.evaluate(() => navigator.clipboard.readText())
    assert.equal(copied.replace(/\r\n/g, '\n'), snippet)
    const selectedCode = '#include <iostream>\nusing namespace'
    await code.click()
    await page.keyboard.press('Control+Home')
    await page.keyboard.down('Shift')
    for (let i = 0; i < selectedCode.length; i++) await page.keyboard.press('ArrowRight')
    await page.keyboard.up('Shift')
    await code.dispatchEvent('mouseup', { button: 0 })
    await toolbar.waitFor()
    await toolbar.getByRole('button', { name: '存为代码卡片' }).waitFor()
    await toolbar.getByRole('button', { name: '在分支中提问' }).click()
    await quoteEditor.waitFor()
    assert.ok((await quoteEditor.innerText()).includes('#include <iostream>'))
    await quoteEditor.fill(selectedCode.split('\n').map(line => '> ' + line).join('\n') + '\n\n' + codeQuote + ' QA_LAYOUT_SCALE')
    await quoteEditor.press('Enter')
    await active(codeQuote + ' QA_LAYOUT_SCALE')
    await editor.waitFor()
    await card.locator('.st-inlet[data-inlet="quote"]').waitFor({ state: 'attached' })
    assert.equal(await card.locator('.st-quote').getAttribute('title'), selectedCode)
    await pick('代码片段')
    await editor.fill(whole + ' QA_LAYOUT_SCALE')
    await editor.press('Enter')
    await active(whole + ' QA_LAYOUT_SCALE')
    await editor.waitFor()
    await card.locator('.st-inlet[data-inlet="card"]').waitFor({ state: 'attached' })
    await pick(root)
    await editor.fill(sibling + ' QA_LAYOUT_SCALE')
    await editor.press('Enter')
    await active(sibling + ' QA_LAYOUT_SCALE')
    await editor.waitFor()
    assert.equal(await reader.getAttribute('data-conversation-session'), sessionId)
    assert.deepEqual(sessionFiles(), originalFiles)
    const requests = fs.readFileSync(path.join(process.env.DSH_QA_OUTPUT, 'native-requests.jsonl'), 'utf8')
      .trim().split('\n').map(line => JSON.parse(line))
    const modelRequest = text => requests.map(request => JSON.stringify(request)).find(request => request.includes(text))
    assert.ok(modelRequest(branch).includes('V1_MARKDOWN_REMAINDER'))
    assert.ok(!modelRequest(branch).includes(newText))
    assert.ok(modelRequest(whole).includes('cout <<'))
    assert.ok(modelRequest(codeQuote).includes('cout <<'))
    assert.ok(!modelRequest(whole).includes(oldText))
    assert.ok(!modelRequest(sibling).includes(oldText) && !modelRequest(sibling).includes('cout <<'))
    await page.reload()
    await pick('复习笔记')
    await card.getByText(newText, { exact: true }).waitFor()
    await pick(branch + ' QA_LAYOUT_SCALE')
    await card.getByRole('button', { name: '定位引用原文：' + oldText }).click()
    await dialog.getByText('提问时的资料 · 第 2 版').waitFor()
    await dialog.getByRole('button', { name: '关闭资料' }).click()
    await pick('代码片段')
    await code.waitFor()
    assert.equal(await codeTools.getByRole('button', { name: '代码语言' }).innerText(), 'C++')
    await page.getByRole('button', { name: '定位当前节点', exact: true }).click()
    await page.waitForFunction(() => document.querySelector('.st-zoom-value')?.textContent === '100%')
    await page.screenshot({ path: path.join(process.env.DSH_QA_OUTPUT, 'material-cards.png') })
    const beforeResize = await card.evaluate(element => ({ width: element.offsetWidth, height: element.offsetHeight }))
    const handle = await card.locator('.react-flow__resize-control.handle.bottom.right').boundingBox()
    assert.ok(handle)
    await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2)
    await page.mouse.down()
    await page.mouse.move(handle.x + handle.width / 2 - 100, handle.y + handle.height / 2 + 120, { steps: 12 })
    await page.mouse.up()
    await page.waitForFunction(before => {
      const current = document.querySelector('.st-card.active')
      return current.classList.contains('sized') && current.offsetHeight > before.height + 90 && current.offsetWidth < before.width - 80
    }, beforeResize)
    const resized = await card.evaluate(element => ({ width: element.offsetWidth, height: element.offsetHeight }))
    await typeSource('')
    await page.waitForFunction(() => document.querySelector('.st-card.active [aria-label="复制代码"]')?.disabled)
    await editor.click()
    await pick(root)
    await pick('代码片段')
    await code.waitFor()
    assert.deepEqual(await card.evaluate(el => ({ width: el.offsetWidth, height: el.offsetHeight })), resized)
    await page.reload()
    await pick('代码片段')
    assert.equal((await contentInput.innerText()).trim(), '粘贴或输入代码…')
    assert.deepEqual(await card.evaluate(el => ({ width: el.offsetWidth, height: el.offsetHeight })), resized)
    assert.deepEqual(errors, [])
    console.log('常驻编辑器、预览、悬浮追问、手动尺寸、划词分支和历史恢复均通过。')
  } catch (error) {
    await page.screenshot({ path: path.join(process.env.DSH_QA_OUTPUT, 'material-cards-failure.png') })
    console.error(errors)
    throw error
  } finally { await browser.close() }
}

main().catch(error => { console.error(error.message.replace(/http\S+/g, '[url]')); process.exitCode = 1 })
